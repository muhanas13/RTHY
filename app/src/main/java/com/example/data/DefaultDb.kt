package com.example.data

data class Student(
    val no: String,
    val username: String,
    val passwordInput: String,
    val name: String,
    val className: String
)

data class TokenInfo(
    val no: String,
    val className: String,
    val subject: String,
    val duration: String,
    val examUrl: String,
    val tokenCode: String
)

object DefaultDb {
    fun parseStudents(csv: String): List<Student> {
        val result = mutableListOf<Student>()
        val lines = csv.lineSequence().map { it.trim() }.filter { it.isNotEmpty() }
        var isHeader = true
        for (line in lines) {
            if (isHeader) {
                isHeader = false
                continue
            }
            // Parse CSV dynamically considering potentially unquoted lines.
            // Split by comma
            val cols = line.split(",")
            if (cols.size >= 5) {
                result.add(
                    Student(
                        no = cols[0].trim(),
                        username = cols[1].trim(),
                        passwordInput = cols[2].trim(),
                        name = cols[3].trim(),
                        className = cols[4].trim()
                    )
                )
            }
        }
        return result
    }

    fun parseTokens(csv: String): List<TokenInfo> {
        val result = mutableListOf<TokenInfo>()
        val lines = csv.lineSequence().map { it.trim() }.filter { it.isNotEmpty() }
        var isHeader = true
        for (line in lines) {
            if (isHeader) {
                isHeader = false
                continue
            }
            val cols = line.split(",")
            if (cols.size >= 6) {
                result.add(
                    TokenInfo(
                        no = cols[0].trim(),
                        className = cols[1].trim(),
                        subject = cols[2].trim(),
                        duration = cols[3].trim(),
                        examUrl = cols[4].trim(),
                        tokenCode = cols[5].trim()
                    )
                )
            }
        }
        return result
    }

